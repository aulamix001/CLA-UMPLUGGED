"""Regenerate the reference bank from the supplied CLUN XML (no proprietary DSP)."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def read_bank():
    names = [p.get("Name") for p in ET.parse(ROOT / "Presets/Reference/parameters.xml").getroot()]
    result = []
    for preset in ET.parse(ROOT / "Presets/Reference/factory.xml").getroot():
        tokens = preset.find("PresetData/Parameters").text.split()
        if len(tokens) != len(names):
            raise ValueError(f"Unexpected parameter count: {preset.get('Name')}")
        values = dict(zip(names, tokens))
        def number(name):
            return float(values["PARAM_" + name])
        stages = ["BASS", "TREBLE", "COMPRESS", "REVERB_1", "REVERB_2", "DELAY"]
        result.append(dict(name=preset.get("Name"), input=number("INPUT_GAIN"),
                           output=number("OUTPUT_GAIN"), balance=number("BALANCE"),
                           direct=number("DRY_OUTPUT_GAIN_DIRECT_IN_OUT") == 0,
                           bypass=number("BYPASS_STATE") != 0,
                           amount=[number(s) for s in stages],
                           colour=[int(number(s + "_COLOR")) for s in stages],
                           note=[int(number(f"PREDELAY_{i}")) for i in (1, 2)],
                           on=[number(f"PREDELAY_{i}_ON_OFF") != 0 for i in (1, 2)]))
    return result


def generate():
    lines = ['// Generated by Tools/ImportReferencePresets.py; do not edit.',
             '#pragma once', '#include "Presets.h"', 'namespace unplugged {',
             'inline void appendReferencePresets(std::vector<Preset>& bank) {']
    def array(values):
        return '{' + ','.join(str(v).lower() if isinstance(v, bool) else str(v) for v in values) + '}'
    for p in read_bank():
        lines += ['    { Settings s;',
                  f'      s.inputDb={p["input"]}; s.outputDb={p["output"]}; s.balance={p["balance"]};',
                  f'      s.amount={array(p["amount"])}; s.colour={array(p["colour"])};',
                  f'      s.preDelayNote={array(p["note"])}; s.preDelayOn={array(p["on"])};',
                  f'      s.direct={str(p["direct"]).lower()}; s.bypass={str(p["bypass"]).lower()};',
                  '      bank.push_back({"XML Reference",' + json.dumps(p['name']) + ',s}); }']
    lines += ['}', '}', '']
    (ROOT / 'Source/ReferencePresets.h').write_text('\n'.join(lines))


if __name__ == '__main__':
    generate()
